#!/usr/bin/env node
// By-hand companion for the FT3 rows. It starts the same digest-pinned
// DynamoDB Local and s3proxy the harness uses, provisions one row's bucket and
// TableTheory-model table, and writes the row's runtime environment to a file
// the documentation's commands source. It never touches another checkout's
// containers: every resource is named ad3-<checkout>-... and carries an owner
// label.

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadRows } from './lib/manifest.mjs';
import { cacheRoot, checkoutId } from './lib/runtime.mjs';
import {
  describeTtl,
  ensureStorageBackends,
  listObjects,
  prepareRowStorage,
  storageNamesForRow,
  stopStorageBackends,
  valueOf,
  getObject,
  scanTable,
} from './lib/storage.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const MANIFEST = path.join(ROOT, 'scripts/local/examples-local.json');

function usage() {
  console.log(`FaceTheory FT3 by-hand storage helper

Usage:
  node scripts/local/isr-storage.mjs up --row <row-id>
  node scripts/local/isr-storage.mjs env --row <row-id>
  node scripts/local/isr-storage.mjs inspect --row <row-id>
  node scripts/local/isr-storage.mjs down

Commands:
  up       start the storage backends and provision the row's bucket/table
  env      print the runtime environment file path for the row
  inspect  print the row's DynamoDB items and S3 objects
  down     remove this checkout's storage containers and network
`);
}

function parseArgs(argv) {
  const options = { command: undefined, row: undefined };
  const [command, ...rest] = argv;
  options.command = command;
  for (let index = 0; index < rest.length; index += 1) {
    if (rest[index] === '--row') {
      options.row = rest[index + 1];
      index += 1;
    } else {
      throw new Error(`unknown argument: ${rest[index]}`);
    }
  }
  return options;
}

function manifest() {
  return JSON.parse(readFileSync(MANIFEST, 'utf8'));
}

function rowFor(id) {
  const row = loadRows(manifest()).find((candidate) => candidate.id === id);
  if (!row) throw new Error(`row not found: ${id}`);
  if (!row.storage) throw new Error(`row ${id} does not use local storage`);
  return row;
}

function envFile(row) {
  return path.join(
    cacheRoot(),
    `ft3-row-${checkoutId(ROOT)}-${storageNamesForRow(row).slug}.env`,
  );
}

function quote(value) {
  return `'${String(value).replaceAll("'", "'\\''")}'`;
}

async function up(row) {
  const storage = await prepareRowStorage({ root: ROOT, manifest: manifest(), row });
  mkdirSync(cacheRoot(), { recursive: true });
  const runtimeEnv = {
    AWS_REGION: 'us-east-1',
    AWS_DEFAULT_REGION: 'us-east-1',
    AWS_ACCESS_KEY_ID: 'dummy',
    AWS_SECRET_ACCESS_KEY: 'dummy',
    AWS_EC2_METADATA_DISABLED: 'true',
    AWS_CONFIG_FILE: '/dev/null',
    AWS_SHARED_CREDENTIALS_FILE: '/dev/null',
    FACETHEORY_EXAMPLES_LOCAL: '1',
    ...storage.env,
  };
  const lines = [
    '# Generated by scripts/local/isr-storage.mjs for the FT3 by-hand run.',
    'unset AWS_PROFILE AWS_SESSION_TOKEN AWS_SECURITY_TOKEN',
    'unset HTTP_PROXY HTTPS_PROXY ALL_PROXY NO_PROXY http_proxy https_proxy all_proxy no_proxy',
    ...Object.entries(runtimeEnv).map(([name, value]) => `export ${name}=${quote(value)}`),
  ];
  writeFileSync(envFile(row), `${lines.join('\n')}\n`);
  console.log(`bucket: ${storage.bucket}`);
  console.log(`table:  ${storage.tableName}`);
  console.log(`prefix: ${storage.prefix || '(none)'}`);
  console.log(`dynamodb: ${storage.endpoints.dynamodb}`);
  console.log(`s3:       ${storage.endpoints.s3}`);
  console.log(`env file: ${envFile(row)}`);
  console.log(`serve:    ( cd ts && set -a && . "${envFile(row)}" && set +a && PORT=${row.port} node --import tsx ${row.serve.args?.[0] ?? ''} )`);
}

function inspectValue(item) {
  const out = {};
  for (const [name, value] of Object.entries(item ?? {})) {
    out[name] = value?.S ?? value?.N ?? value?.BOOL ?? value;
  }
  return out;
}

async function inspect(row) {
  const backends = await ensureStorageBackends({ root: ROOT, manifest: manifest() });
  const names = storageNamesForRow(row);
  const items = await scanTable({
    endpoint: backends.endpoints.dynamodb,
    tableName: names.tableName,
  });
  const ttl = await describeTtl({
    endpoint: backends.endpoints.dynamodb,
    tableName: names.tableName,
  });
  console.log(`table: ${names.tableName}`);
  console.log(`ttl:   ${ttl.TimeToLiveStatus} ${ttl.AttributeName ?? ''}`.trim());
  console.log(`items: ${items.length}`);
  for (const item of items) {
    console.log(JSON.stringify(inspectValue(item)));
  }
  const keys = await listObjects({
    endpoint: backends.endpoints.s3,
    bucket: names.bucket,
  });
  console.log(`objects: ${keys.length}`);
  for (const key of keys) {
    const object = await getObject({
      endpoint: backends.endpoints.s3,
      bucket: names.bucket,
      key,
    });
    const text = object.body.toString('utf8');
    console.log(
      JSON.stringify({
        key,
        bytes: object.body.length,
        contentType: object.contentType,
        cacheControl: object.cacheControl,
        metadata: object.metadata,
        body: text.length > 240 ? `${text.slice(0, 240)}…` : text,
      }),
    );
  }
  const meta = items.find((item) => valueOf(item, 'sk') === 'META');
  if (meta) {
    console.log(`metadata pointer: ${String(valueOf(meta, 's3_key'))}`);
  }
}

async function down() {
  const results = await stopStorageBackends({ root: ROOT, manifest: manifest() });
  for (const result of results) {
    console.log(`${result.stopped ? 'removed' : 'left'} ${result.name}: ${result.reason}`);
  }
  const cache = cacheRoot();
  if (existsSync(cache)) {
    for (const name of readdirSync(cache)) {
      if (name.startsWith(`ft3-row-${checkoutId(ROOT)}-`) && name.endsWith('.env')) {
        rmSync(path.join(cache, name), { force: true });
      }
    }
  }
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (!options.command || options.command === '--help' || options.command === '-h') {
    usage();
    return;
  }
  if (options.command === 'down') {
    await down();
    return;
  }
  if (!options.row) throw new Error(`${options.command} requires --row <row-id>`);
  const row = rowFor(options.row);
  if (options.command === 'up') await up(row);
  else if (options.command === 'env') console.log(envFile(row));
  else if (options.command === 'inspect') await inspect(row);
  else throw new Error(`unknown command: ${options.command}`);
}

main().catch((error) => {
  console.error(`isr-storage: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
